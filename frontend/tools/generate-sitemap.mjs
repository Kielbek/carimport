// Generates public/sitemap.xml: every indexable page in every language, each with hreflang alternates.
// Reads the language list (core/i18n/languages.ts) and localized slugs (core/routing/paths.ts), so it stays in sync
// with the router. Run after adding a language or a page:  node tools/generate-sitemap.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const SITE = 'https://cargloapp.com';
const src = (p) => readFileSync(new URL(`../src/app/${p}`, import.meta.url), 'utf8');

const langs = [...src('core/i18n/languages.ts').matchAll(/\{ code: '([a-z]{2})'/g)].map((m) => m[1]);
const pathsTs = src('core/routing/paths.ts');
const slugBlock = (page) => {
  const start = pathsTs.indexOf(`  ${page}: {`);
  const body = pathsTs.slice(start, pathsTs.indexOf('},', start));
  return Object.fromEntries([...body.matchAll(/([a-z]{2}): '([^']+)'/g)].map((m) => [m[1], m[2]]));
};
const pages = [
  { key: 'home', slugs: Object.fromEntries(langs.map((l) => [l, ''])), freq: 'weekly', priority: '1.0' },
  { key: 'calculator', slugs: slugBlock('calculator'), freq: 'weekly', priority: '0.9' },
  { key: 'about', slugs: slugBlock('about'), freq: 'monthly', priority: '0.6' },
  { key: 'privacy', slugs: slugBlock('privacy'), freq: 'yearly', priority: '0.2' },
  { key: 'terms', slugs: slugBlock('terms'), freq: 'yearly', priority: '0.2' },
];
// SEO guides: hubs and items, slugs from core/routing/guide-paths.ts and the generated guide data
const guidePathsTs = src('core/routing/guide-paths.ts');
const guideData = src('features/guides/guide-data.generated.ts');
const sections = Object.fromEntries([...guidePathsTs.matchAll(/^  ([a-z]{2}): \{ origins: '([^']+)', countries: '([^']+)', ports: '([^']+)' \}/gm)]
  .map((m) => [m[1], { origins: m[2], countries: m[3], ports: m[4] }]));
const json = (name) => JSON.parse(guideData.match(new RegExp(`export const ${name}[^=]*= (.*);`))[1]);
const countrySlugs = json('COUNTRY_SLUGS');
const originSlugs = json('ORIGIN_SLUGS');
const ports = json('GUIDE_PORTS');
const items = {
  origins: Object.keys(originSlugs.en).map((o) => (l) => originSlugs[l][o]),
  countries: Object.keys(countrySlugs.en).map((c) => (l) => countrySlugs[l][c]),
  ports: ports.map((p) => () => p.slug),
};
for (const section of ['origins', 'countries', 'ports']) {
  pages.push({ key: section, slugs: Object.fromEntries(langs.map((l) => [l, sections[l][section]])), freq: 'weekly', priority: '0.8' });
  for (const item of items[section]) {
    pages.push({ key: section, slugs: Object.fromEntries(langs.map((l) => [l, `${sections[l][section]}/${item(l)}`])), freq: 'monthly', priority: '0.7' });
  }
}

// blog: the list in every language, articles only in the languages that have them (hreflang among those)
const blogIndex = src('features/blog/blog-index.generated.ts');
const blogJson = (name) => JSON.parse(blogIndex.match(new RegExp(`export const ${name}[^=]*= ([\\s\\S]*?);\\n`))[1]);
const BLOG_INDEX = blogJson('BLOG_INDEX');
const BLOG_DATES = blogJson('BLOG_DATES');
pages.push({ key: 'blog', slugs: Object.fromEntries(langs.map((l) => [l, 'blog'])), freq: 'weekly', priority: '0.8' });

const url = (lang, slug) => `${SITE}/${lang}${slug ? '/' + slug : ''}`;

let xml = '<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by tools/generate-sitemap.mjs - do not edit by hand -->\n'
  + '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n';
for (const page of pages) {
  for (const lang of langs) {
    xml += `  <url>\n    <loc>${url(lang, page.slugs[lang])}</loc>\n`;
    for (const alt of langs) {
      xml += `    <xhtml:link rel="alternate" hreflang="${alt}" href="${url(alt, page.slugs[alt])}"/>\n`;
    }
    xml += `    <xhtml:link rel="alternate" hreflang="x-default" href="${url('en', page.slugs.en)}"/>\n`;
    xml += `    <changefreq>${page.freq}</changefreq><priority>${page.priority}</priority>\n  </url>\n`;
  }
}
for (const [id, versions] of Object.entries(BLOG_INDEX)) {
  const vlangs = Object.keys(versions);
  for (const lang of vlangs) {
    xml += `  <url>\n    <loc>${url(lang, 'blog/' + versions[lang])}</loc>\n    <lastmod>${BLOG_DATES[id]}</lastmod>\n`;
    for (const alt of vlangs) {
      xml += `    <xhtml:link rel="alternate" hreflang="${alt}" href="${url(alt, 'blog/' + versions[alt])}"/>\n`;
    }
    xml += `    <changefreq>monthly</changefreq><priority>0.7</priority>\n  </url>\n`;
  }
}
xml += '</urlset>\n';
writeFileSync(new URL('../public/sitemap.xml', import.meta.url), xml);
console.log(`sitemap: ${xml.split("<loc>").length - 1} URLs in ${langs.length} languages (${xml.length >> 10} kB)`);
