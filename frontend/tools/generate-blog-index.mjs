// Generates src/app/features/blog/blog-index.generated.ts from src/content/blog/{lang}.json:
// for every article id, its slug in each language that has it (hreflang, prerender params, sitemap).
// Run after adding or editing articles:  node tools/generate-blog-index.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('../src/content/blog/', import.meta.url);
const index = {};
const dates = {};
for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const lang = file.replace('.json', '');
  const articles = JSON.parse(readFileSync(new URL(file, dir), 'utf8'));
  const slugs = new Set();
  for (const a of articles) {
    if (slugs.has(a.slug)) throw new Error(`${lang}: duplicate slug ${a.slug}`);
    slugs.add(a.slug);
    (index[a.id] ??= {})[lang] = a.slug;
    dates[a.id] = a.date;
  }
}
const langs = [...new Set(Object.values(index).flatMap((m) => Object.keys(m)))].sort();
writeFileSync(new URL('../src/app/features/blog/blog-index.generated.ts', import.meta.url),
  `// Generated by tools/generate-blog-index.mjs - do not edit by hand.

/** Article id -> language -> slug. */
export const BLOG_INDEX: Record<string, Record<string, string>> = ${JSON.stringify(index, null, 2)};

/** Article id -> publication date (for the sitemap). */
export const BLOG_DATES: Record<string, string> = ${JSON.stringify(dates)};

/** Languages that have at least one article. */
export const BLOG_LANGS: string[] = ${JSON.stringify(langs)};
`);
console.log(`blog: ${Object.keys(index).length} articles, ${langs.length} languages, ${Object.values(index).reduce((n, m) => n + Object.keys(m).length, 0)} pages`);
