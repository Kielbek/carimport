// Generates src/app/features/eu-import/eu-routes.generated.ts: example costs for the intra-EU route pages
// (/pl/import-auta-z-ue/niemcy-polska, ...), priced by the real EU import engine of a running backend.
//   node tools/generate-eu-routes.mjs [http://localhost:8080]
// Routes and example cars: tools/eu-routes.json. Re-run when rates or routes change.
import { readFileSync, writeFileSync } from 'node:fs';

const api = (process.argv[2] ?? 'http://localhost:8080') + '/api/v1/quotes/eu';
const cfg = JSON.parse(readFileSync(new URL('./eu-routes.json', import.meta.url), 'utf8'));
const guide = readFileSync(new URL('../src/app/features/guides/guide-data.generated.ts', import.meta.url), 'utf8');
const json = (name) => JSON.parse(guide.match(new RegExp(`export const ${name}[^=]*= ([\\s\\S]*?);\\n`))[1]);
const slugs = json('COUNTRY_SLUGS');
const currencyOf = Object.fromEntries(json('GUIDE_COUNTRIES').map((c) => [c.code, c.currency]));
const DISPLAY = new Set(['EUR', 'PLN', 'CZK', 'HUF', 'RON', 'SEK', 'DKK']);

async function quote(from, to, car, mode) {
  const currency = DISPLAY.has(currencyOf[to]) ? currencyOf[to] : 'EUR';
  const body = {
    originCountry: from, destinationCountry: to, price: car.price, priceCurrency: 'EUR', displayCurrency: currency,
    productionYear: car.year, fuelType: car.fuel, engineCc: car.cc, vehicleCategory: 'PASSENGER_CAR', powerKw: car.kw,
    co2Gkm: car.co2, massKg: null, newVehicle: false, deliveryMode: mode, distanceKm: null,
  };
  let res;
  for (;;) {
    res = await fetch(api, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    if (res.status !== 429) break;
    // the public API allows ~20 quotes a minute per client: wait as told and retry
    await new Promise((r) => setTimeout(r, (Number(res.headers.get('retry-after')) || 3) * 1000 + 200));
  }
  if (!res.ok) throw new Error(`${from}->${to} ${car.id} ${mode}: HTTP ${res.status} ${await res.text()}`);
  return res.json();
}

const round = (n) => Math.round(n);
const routes = [];
for (const [lang, dests] of Object.entries(cfg.routes)) {
  for (const [to, froms] of Object.entries(dests)) {
    for (const from of froms) {
      const examples = [];
      let km = 0, currency = 'EUR', fxDate = '';
      for (const car of cfg.cars) {
        const r = await quote(from, to, car, 'CAR_CARRIER');
        km = r.distanceKm; currency = r.currency; fxDate = r.fxDate;
        examples.push({
          car: car.id, priceEur: car.price, year: car.year, fuel: car.fuel, cc: car.cc, kw: car.kw, co2: car.co2,
          lines: r.lines.filter((l) => l.includedInTotal).map((l) => ({ code: l.code, amount: round(l.amount.amount), rate: l.rate, params: l.params ?? {} })),
          total: round(r.total.amount),
          warnings: r.warnings,
        });
      }
      const transport = {};
      for (const mode of ['CAR_CARRIER', 'TOW_TRUCK', 'SELF_DRIVE']) {
        const r = await quote(from, to, cfg.cars[0], mode);
        transport[mode] = r.lines.filter((l) => l.category === 'TRANSPORT').reduce((s, l) => s + l.amount.amount, 0);
        transport[mode] = round(transport[mode]);
      }
      routes.push({ lang, from, to, slug: `${slugs[lang][from]}-${slugs[lang][to]}`, km, currency, fxDate, examples, transport });
      process.stdout.write(`${lang} ${from}->${to} ${km} km ${examples.map((e) => e.total).join('/')} ${currency}\n`);
    }
  }
}

const out = `// Generated by tools/generate-eu-routes.mjs from tools/eu-routes.json - do not edit.

import { EuRoute } from './eu-route-types';

export const EU_ROUTES_DATE = '${new Date().toISOString().slice(0, 10)}';

export const EU_ROUTES: EuRoute[] = ${JSON.stringify(routes)};
`;
writeFileSync(new URL('../src/app/features/eu-import/eu-routes.generated.ts', import.meta.url), out);
console.log(`eu routes: ${routes.length}`);
