/**
 * Example costs for the SEO model pages (/pl/koszt-importu/ford-mustang, ...): every model of frontend/tools/models.json
 * imported to the home country of every language, through the cheapest port, priced by the real engine in that
 * country's currency. Writes frontend/src/app/features/guides/model-data.generated.ts. Run when rates change:
 * {@code java -jar app.jar --spring.profiles.active=models --models.in=../frontend/tools/models.json
 * --models.out=../frontend/src/app/features/guides/model-data.generated.ts}
 */
@Component
@Profile("models")
public class ModelExampleGenerator implements CommandLineRunner {

    private static final Logger log = LoggerFactory.getLogger(ModelExampleGenerator.class);

    /** Destination of each language's pages (English: Germany, Ukrainian: Poland - as in the calculator). */
    static final List<String> COUNTRIES = List.of("BG", "CZ", "DK", "DE", "GR", "ES", "EE", "FI", "FR", "HR", "HU",
            "IT", "LT", "LV", "NL", "PL", "PT", "RO", "SK", "SI", "SE");
    private static final Map<String, CurrencyCode> CURRENCY = Map.of("PL", CurrencyCode.PLN, "CZ", CurrencyCode.CZK,
            "DK", CurrencyCode.DKK, "HU", CurrencyCode.HUF, "RO", CurrencyCode.RON, "SE", CurrencyCode.SEK);

    private final CalculationEngine engine;
    private final SuggestionService suggestions;
    private final ExchangeRateService rates;
    private final ObjectMapper json;
    private final ConfigurableApplicationContext context;
    private final Path in;
    private final Path out;

    public ModelExampleGenerator(CalculationEngine engine, SuggestionService suggestions, ExchangeRateService rates,
                                 ObjectMapper json, ConfigurableApplicationContext context,
                                 @Value("${models.in:../frontend/tools/models.json}") String in,
                                 @Value("${models.out:../frontend/src/app/features/guides/model-data.generated.ts}") String out) {
        this.engine = engine;
        this.suggestions = suggestions;
        this.rates = rates;
        this.json = json;
        this.context = context;
        this.in = Path.of(in);
        this.out = Path.of(out);
    }

    @Override
    public void run(String... args) throws IOException {
        JsonNode models = json.readTree(in.toFile()).get("models");
        FxRates fx = rates.latest();
        ObjectNode examples = json.createObjectNode();
        for (JsonNode m : models) {
            ObjectNode perCountry = examples.putObject(m.get("id").asText());
            for (String country : COUNTRIES) {
                CurrencyCode currency = CURRENCY.getOrDefault(country, CurrencyCode.EUR);
                String port = suggestions.suggest(request(m, country, currency, "DEBRV")).recommendedPort();
                QuoteRange range = engine.calculateRange(request(m, country, currency, port), fx);
                perCountry.set(country, example(range, port, country, currency));
            }
            log.info("Model {} priced for {} countries", m.get("id").asText(), COUNTRIES.size());
        }
        String ts = "// Generated by com.carimport.seo.ModelExampleGenerator from frontend/tools/models.json - do not edit.\n\n"
                + "import { GuideModel, ModelExample } from './model-types';\n\n"
                + "export const MODEL_EXAMPLES_DATE = '" + LocalDate.now() + "';\n\n"
                + "export const GUIDE_MODELS: GuideModel[] = " + json.writeValueAsString(models) + ";\n\n"
                + "/** model id -> destination country -> example (amounts in the country's currency). */\n"
                + "export const MODEL_EXAMPLES: Record<string, Record<string, ModelExample>> = "
                + json.writeValueAsString(examples) + ";\n";
        Files.writeString(out, ts);
        log.info("Wrote {} ({} kB)", out, ts.length() >> 10);
        context.close();
    }

    private ObjectNode example(QuoteRange range, String port, String country, CurrencyCode currency) {
        CalculationResult r = range.expected();
        TaxSummary taxes = TaxSummary.of(r, port.substring(0, 2), country);
        BigDecimal price = category(r, CostCategory.VEHICLE);
        BigDecimal transport = category(r, CostCategory.TRANSPORT);
        BigDecimal registration = category(r, CostCategory.REGISTRATION);
        BigDecimal national = taxes.national().stream().map(TaxSummary.Item::amount).reduce(BigDecimal.ZERO, BigDecimal::add);
        BigDecimal total = whole(r.total().amount());
        BigDecimal other = total.subtract(price).subtract(transport).subtract(registration)
                .subtract(taxes.duty().amount()).subtract(taxes.vat().amount()).subtract(national);
        ObjectNode e = json.createObjectNode();
        e.put("currency", currency.name());
        e.put("port", r.route().euPortName());
        e.put("portCode", port);
        e.put("departure", r.route().departurePort());
        ArrayNode days = e.putArray("days");
        days.add(r.timeline().totalMin()).add(r.timeline().totalMax());
        e.put("price", price);
        e.put("transport", transport);
        e.put("duty", taxes.duty().amount());
        e.put("vat", taxes.vat().amount());
        e.put("vatRate", taxes.vat().rate());
        ArrayNode nat = e.putArray("national");
        taxes.national().forEach(i -> nat.addObject().put("code", i.code()).put("amount", i.amount()));
        e.put("registration", registration);
        e.put("other", other.max(BigDecimal.ZERO));
        e.put("total", round(total));
        e.put("low", round(whole(range.low().total().amount())));
        e.put("high", round(whole(range.high().total().amount())));
        return e;
    }

    private static CalculationRequest request(JsonNode m, String country, CurrencyCode currency, String port) {
        OriginCountry origin = OriginCountry.valueOf(m.get("origin").asText());
        return new CalculationRequest(origin, AuctionHouse.valueOf(m.get("auction").asText()), TitleType.CLEAN,
                m.get("zone").asText(), null, new BigDecimal(m.get("price").asText()),
                VehicleCategory.valueOf(m.get("category").asText()), FuelType.valueOf(m.get("fuel").asText()),
                m.get("cc").asInt(), m.get("year").asInt(), false, VehicleCondition.RUN_AND_DRIVE,
                ShippingMethod.CONTAINER_SHARED, port, country, BuyerType.PRIVATE, CustomsProcedure.STANDARD_4000,
                currency, null, null, null, BigDecimal.ZERO, null, null, null, null, null,
                m.get("co2").asInt(), m.get("kw").asInt(), null, m.get("kg").asInt(), null,
                m.get("year").asInt() + " " + m.get("make").asText() + " " + m.get("model").asText());
    }

    private static BigDecimal category(CalculationResult r, CostCategory category) {
        return r.lines().stream()
                .filter(l -> l.line().category() == category && l.line().includedInTotal())
                .map(l -> l.display().amount())
                .reduce(BigDecimal.ZERO, BigDecimal::add)
                .setScale(0, RoundingMode.HALF_UP);
    }

    private static BigDecimal whole(BigDecimal amount) {
        return amount.setScale(0, RoundingMode.HALF_UP);
    }

    private static BigDecimal round(BigDecimal amount) {
        return amount.divide(BigDecimal.valueOf(TaxSummary.ESTIMATE_STEP), 0, RoundingMode.HALF_UP)
                .multiply(BigDecimal.valueOf(TaxSummary.ESTIMATE_STEP));
    }
}
